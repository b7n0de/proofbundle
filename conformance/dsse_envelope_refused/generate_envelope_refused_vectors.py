#!/usr/bin/env python3
"""Generate the envelope-refused vectors: a DSSE envelope refused before any signature check.

Run ONCE, the fixtures are committed bytes. This script writes ONLY the case directories under
``conformance/dsse_envelope_refused/`` and appends them to ``conformance/manifest.json``. It borrows
the predicate bases and the case layout of ``conformance/relation/generate_vectors.py`` and never
touches its vectors. The cases run on the relation verify paths (kinds decision_relation,
outcome_relation, relation_statement) but test the DSSE envelope, not a relation, so they live in a
directory of their own.

Why the class exists in the corpus. ``decision verify``, ``outcome verify`` and
``relation-statement verify`` name exit 2 for malformed input and exit 1 for a crypto failure.
An envelope whose payload does not decode, whose fields are missing or of the wrong type, or
which is no object at all is refused before any signature is checked, so it is malformed input
(exit 2), never a crypto failure. The Python CLI and the Rust second verifier
(``tools/pb_verify_rs``, ``verify-relation`` / ``verify-relation-statement``) must say so in the
same words of the common vocabulary. Before these vectors the corpus held no such envelope, and
``tools/pb_verify_rs/crosscheck.py`` could not see the two verifiers disagree on it: measured on
2026-11-07, with the Python change alone the two sides differed in 36 of 52 shapes and every
parity test of the repository stayed green.

Per command eleven malformed shapes (expected exit 2, lineage NOT_EVALUATED) and two controls
built from the same signed envelope (expected exit 0): the intact envelope, and the same
payload bytes re-encoded in the URL-safe alphabet with padding, which both verifiers accept.
Cases of the same shape share a ``crossFormatId`` across the three commands, so the
cross-format comparator holds their declared verdicts to one value.

All signing keys are FRESH THROWAWAY TEST KEYS generated at build time and never stored; the
public key is recorded in each case's pub.b64. Regeneration changes bytes: rerun, review the
diff, recommit. Never hand-edit generated fixtures.
"""
from __future__ import annotations

import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "src"))
sys.path.insert(0, str(HERE.parent / "relation"))

from generate_vectors import (  # noqa: E402
    BASE_PRED,
    OUTCOME_BASE,
    base_case,
    pub_of,
)

from proofbundle.decision import emit_decision_receipt  # noqa: E402
from proofbundle.emit import generate_signer  # noqa: E402
from proofbundle.outcome import emit_outcome_receipt  # noqa: E402
from proofbundle.relation_statement import emit_relation_statement  # noqa: E402

ATTRIBUTION = ("b7n0de / envelope-refused corpus generator "
               "(conformance/dsse_envelope_refused/generate_envelope_refused_vectors.py, 2026-11-07)")
TEST_KEYS = ("fresh throwaway keys, generated by "
             "conformance/dsse_envelope_refused/generate_envelope_refused_vectors.py")
SIGNATURE_BUDGET = 512  # proofbundle.dsse: at most 512 signatures are read

#: The two relation documents ``base_case`` names, here by URL. The sdist ships neither, and
#: tests/test_ausgelieferte_doku_haelt.py holds the number of specRefs that point at an unshipped
#: file to a frozen baseline. The 39 relative references of these cases grew it from 153 to 231
#: (CI hermetic-cleanroom of PR 563, 2026-11-25, measured in the extracted sdist). Shipping the two
#: documents is a packaging decision of the owner; an absolute URL names the same text without
#: growing the gap, as conformance/envelope_profile/generate_vectors.py does for SPEC.md.
SPEC_REFS = ["https://github.com/b7n0de/proofbundle/blob/main/docs/predicates/relation.md",
             "https://github.com/b7n0de/proofbundle/blob/main/docs/design/RELATION_V01_DESIGN.md"]

#: command -> (directory tag, case kind, caseId tag)
COMMANDS = {
    "decision": ("decision", "decision_relation", "decision"),
    "outcome": ("outcome", "outcome_relation", "outcome"),
    "relation-statement": ("statement", "relation_statement", "statement"),
}


def write_case(name: str, files: dict, case: dict) -> None:
    """The layout of ``generate_vectors.write_case``, written under this directory."""
    d = HERE / name
    d.mkdir(parents=True, exist_ok=True)
    for fname, obj in files.items():
        if isinstance(obj, (dict, list)):
            (d / fname).write_text(json.dumps(obj, indent=1, ensure_ascii=False) + "\n",
                                   encoding="utf-8")
        else:
            (d / fname).write_text(str(obj), encoding="utf-8")
    (d / "case.json").write_text(json.dumps(case, indent=2, ensure_ascii=False) + "\n",
                                 encoding="utf-8")
    print("wrote", name)


def _usable(env: dict) -> bool:
    """The base envelope must carry a payload that ends in padding (so dropping it is a real
    shape) and holds a '+' or '/' (so the URL-safe form differs from the standard one)."""
    p = env["payload"]
    return p.endswith("=") and ("+" in p or "/" in p)


def _first_usable(make) -> dict:
    # The statement is ASCII JSON, and base64 of ASCII text yields '+' or '/' only where a '>' or
    # '?' is the third byte of a three-byte group. The varied field therefore ends in '???', so one
    # of the three lands there, and its growing length moves the payload onto and off padding.
    for i in range(1, 400):
        env = make("x" * i + "???")
        if _usable(env):
            return env
    raise SystemExit("no usable base envelope found")


def base_envelopes(signer) -> dict:
    def decision(n):
        pred = json.loads(json.dumps(BASE_PRED))
        pred["decisionId"] = f"d-envelope-refused-{n}"
        return emit_decision_receipt(pred, signer, strict=True)

    def outcome(n):
        pred = json.loads(json.dumps(OUTCOME_BASE))
        pred["outcomeId"] = "urn:uuid:11111111-1111-1111-1111-11111111e0f1"
        pred["executor"] = {"id": f"executor://example/envelope-refused-{n}"}
        return emit_outcome_receipt(pred, signer, strict=True)

    def statement(n):
        return emit_relation_statement({
            "schemaVersion": "0.1.0",
            "statementId": f"urn:uuid:stmt-envelope-refused-{n}",
            "relationships": [{
                "relation": "retracts",
                "targetReceiptDigest": {"digestAlgorithm": "jcs-sha256-v1", "digest": "d" * 64},
                "reasonCode": "withdrawal", "reason": "envelope-refused control",
                "declaredAt": "2026-09-29T00:00:00Z"}]}, signer)

    return {"decision": _first_usable(decision), "outcome": _first_usable(outcome),
            "relation-statement": _first_usable(statement)}


def _urlsafe(payload: str) -> str:
    return payload.replace("+", "-").replace("/", "_")


def shapes(env: dict):
    """(slug, envelope, what it is). Every shape is refused before any signature is checked."""
    sig = env["signatures"][0]["sig"]
    yield ("payload-unpadded", dict(env, payload=env["payload"].rstrip("=")),
           "the payload in the standard alphabet without its trailing '=' padding (F95)")
    yield ("payload-urlsafe-unpadded", dict(env, payload=_urlsafe(env["payload"]).rstrip("=")),
           "the payload in the URL-safe alphabet without its trailing '=' padding")
    yield ("payload-foreign-char", dict(env, payload="!" + env["payload"][1:]),
           "the payload with a character outside both base64 alphabets ('!')")
    yield ("payload-not-string", dict(env, payload=12),
           "the payload is a JSON number, not a base64 string")
    yield ("payload-missing", {k: v for k, v in env.items() if k != "payload"},
           "the payload field is missing")
    yield ("payloadtype-missing", {k: v for k, v in env.items() if k != "payloadType"},
           "the payloadType field is missing")
    yield ("signatures-empty", dict(env, signatures=[]),
           "the signatures list is empty")
    yield ("signatures-missing", {k: v for k, v in env.items() if k != "signatures"},
           "the signatures field is missing")
    yield ("signatures-not-list", dict(env, signatures={"sig": sig}),
           "signatures is an object, not a list")
    yield ("signatures-over-budget", dict(env, signatures=[dict(env["signatures"][0])
                                                          for _ in range(SIGNATURE_BUDGET + 1)]),
           f"{SIGNATURE_BUDGET + 1} signatures, one over the budget of {SIGNATURE_BUDGET}")
    yield ("envelope-not-object", [env],
           "the envelope is a JSON array holding the envelope, not an object")


def main() -> None:
    signer = generate_signer()
    pub_b64 = pub_of(signer)
    written = []
    for command, env in base_envelopes(signer).items():
        tag, kind, id_tag = COMMANDS[command]
        for slug, bad, what in shapes(env):
            name = f"{tag}-{slug}"
            write_case(name, {"receipt.json": bad, "pub.b64": pub_b64},
                       dict(base_case(
                           f"dsse-envelope-refused-{id_tag}-{slug}",
                           {"exitCode": 2, "lineage": "NOT_EVALUATED"},
                           f"A DSSE envelope refused before any signature check, on `{command} "
                           f"verify`: {what}. The verify contract names exit 2 for malformed input "
                           f"and exit 1 for a crypto failure; no signature was checked, so this is "
                           f"malformed input on BOTH verifiers (Python CLI and pb_verify_rs), lineage "
                           f"not evaluated. Measured 2026-11-07 before this class was in the corpus: "
                           f"both verifiers answered 1, and with the Python fix alone Python answered "
                           f"2 and Rust 1 while every parity test stayed green.",
                           kind=kind, cross_format_id=f"xfmt-envelope-refused-{slug}",
                           attribution=ATTRIBUTION), testKeys=TEST_KEYS, specRefs=SPEC_REFS))
            written.append(f"dsse_envelope_refused/{name}")
        for slug, good, what in (
            ("intact", env, "the intact envelope as emitted, payload in the standard alphabet "
                            "with padding"),
            ("urlsafe-padded", dict(env, payload=_urlsafe(env["payload"])),
             "the SAME payload bytes re-encoded in the URL-safe alphabet WITH padding, the "
             "signature unchanged (it signs the decoded bytes)"),
        ):
            name = f"{tag}-control-{slug}"
            write_case(name, {"receipt.json": good, "pub.b64": pub_b64},
                       dict(base_case(
                           f"dsse-envelope-control-{id_tag}-{slug}",
                           {"exitCode": 0},
                           f"Positive control of the envelope-refused class on `{command} verify`: "
                           f"{what}. Both verifiers accept it (exit 0), so the refusals of the same "
                           f"envelope next to it are about the envelope's form and nothing else.",
                           kind=kind, cross_format_id=f"xfmt-envelope-control-{slug}",
                           attribution=ATTRIBUTION), testKeys=TEST_KEYS, specRefs=SPEC_REFS))
            written.append(f"dsse_envelope_refused/{name}")
    # The manifest lists every case; append the ones this script owns that it does not list yet,
    # in the order written, and leave every other entry exactly where it is.
    manifest_path = HERE.parent / "manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    missing = [c for c in written if c not in manifest["cases"]]
    if missing:
        manifest["cases"].extend(missing)
        manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
                                 encoding="utf-8")
    print("done,", len(written), "cases,", len(missing), "added to manifest.json")


if __name__ == "__main__":
    main()
