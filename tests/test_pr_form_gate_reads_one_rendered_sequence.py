"""K8 (Codex defect search on the 6.3.0 candidate 98b168b9, CODEX-630-K8): the form gate judges the attribution on
one rendered sequence, not per parser segment.

`_has_attribution` read each run of inline content on its own and forgot the text before a link at the end of a
run. `Generated by`, an empty line and `[ExampleTool](https://tool.example/)` was green/0, while the HTML that
CommonMark renders from it, `<p>Generated by</p>\\n<p><a href=...>ExampleTool</a></p>`, byte for byte the same,
was RED/1 with rule (c), because an HTML block is one segment (measured by Codex at 98b168b9 with markdown-it-py).
The runs below are the ones `_rendered` yields for the two forms; the cases through the parser itself need
markdown-it-py and skip without it. The address is a placeholder and is parsed as text only.
"""
from __future__ import annotations

import importlib.util
import json
import pathlib
import types

import pytest

REPO = pathlib.Path(__file__).resolve().parents[1]
_PATH = REPO / "scripts" / "b7_pr_form_gate.py"
pytestmark = pytest.mark.skipif(not _PATH.is_file(), reason="scripts/b7_pr_form_gate.py is not in this tree")


def _gate():
    spec = importlib.util.spec_from_file_location("_k8_pr_form_gate", _PATH)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


GATE = _gate() if _PATH.is_file() else None
ADDRESS = "https://tool.example/"
FOOTER = "Written by an AI session of b7n0de under owner review.\n\nMeasurement, not certification."
MARKDOWN = "Generated by\n\n[ExampleTool](" + ADDRESS + ")"
HTML = '<p>Generated by</p>\n<p><a href="' + ADDRESS + '">ExampleTool</a></p>'

# What `_rendered` yields: Markdown gives one run per paragraph, an HTML block one run with its text and anchors.
RUNS_MARKDOWN = [[("text", "Generated by")], [("link", ADDRESS), ("text", "ExampleTool")]]
RUNS_HTML = [[("text", "Generated by"), ("text", "\n"), ("link", ADDRESS), ("text", "ExampleTool")]]
RUNS_PROSE = [[("text", "A change was generated by hand.")], [("link", ADDRESS), ("text", "ExampleTool")]]


def test_RED_the_words_at_the_end_of_one_block_and_the_link_in_the_next_are_an_attribution():
    """T8, the Markdown form."""
    assert GATE._has_attribution(RUNS_MARKDOWN) is True


def test_RED_the_words_and_a_bare_address_in_the_next_block_are_an_attribution():
    assert GATE._has_attribution([[("text", "Generated with")], [("text", ADDRESS)]]) is True


def test_CONTROL_the_html_form_stays_an_attribution():
    assert GATE._has_attribution(RUNS_HTML) is True


def test_CONTROL_prose_that_names_no_link_after_the_words_stays_green():
    """Codex's positive control: `A change was generated by hand.` before the same link."""
    assert GATE._has_attribution(RUNS_PROSE) is False


def test_CONTROL_a_link_in_between_still_ends_the_words_before_it():
    """`Generated`, a link, then `by` and a link in later blocks: the words never stand together before a link."""
    runs = [[("text", "Generated "), ("link", "https://other.example/")], [("text", "by")], [("link", ADDRESS)]]
    assert GATE._has_attribution(runs) is False


def test_CONTROL_a_word_cut_by_the_carry_does_not_become_the_phrase():
    """The carried end is cut at a word boundary: `regenerated by` with a long address after it is no phrase."""
    runs = [[("text", "x" * 200 + " regenerated by")], [("link", ADDRESS)]]
    assert GATE._has_attribution(runs) is False


def test_CONTROL_the_carry_never_starts_inside_a_word():
    """The carried end is the last 64 folded characters; cut there, `regenerated by` and an address of the right
    length would begin with `generated by` and meet the next block as a phrase that is not in the text."""
    address = ADDRESS + "a" * (64 - len("generated by ") - len(ADDRESS))
    text = "regenerated by " + address
    assert len(GATE._norm(text)) - len("re") == 64, "precondition: the last 64 characters start at 'generated'"
    assert GATE._has_attribution([[("text", text)], [("text", "next")]]) is False


def test_RED_a_code_block_between_the_words_and_the_link_is_rendered_text(monkeypatch):
    """The same class in `_rendered`: a fenced code block was left out of the sequence, so the words before it
    and the link after it met, where the HTML form carries the code text between them. Through a stand-in for
    the parser that yields markdown-it's token types; the real parser is used below when it is installed."""
    tokens = [types.SimpleNamespace(type="inline", children=[types.SimpleNamespace(type="text", content="Generated by")]),
              types.SimpleNamespace(type="fence", content="not a link\n", children=None),
              types.SimpleNamespace(type="inline", children=[types.SimpleNamespace(
                  type="link_open", content="", attrGet=lambda _name: ADDRESS)])]

    class StandIn:
        def __init__(self, *_args):
            pass

        def parse(self, _body):
            return tokens

    monkeypatch.setattr(GATE, "MarkdownIt", StandIn)
    laeufe, _ziele = GATE._rendered("ignored by the stand-in")
    assert ("text", "not a link\n") in [item for lauf in laeufe for item in lauf]
    assert GATE._has_attribution(laeufe) is False


def _event(tmp_path, before: str) -> pathlib.Path:
    event = tmp_path / "event.json"
    event.write_text(json.dumps({"action": "edited", "pull_request": {
        "number": 1, "milestone": {"number": 2, "title": "6.3.0", "state": "open"},
        "body": before + "\n\n" + FOOTER}}), encoding="utf-8")
    return event


@pytest.mark.parametrize("before, expected", [(MARKDOWN, 1), (HTML, 1), ("A change was generated by hand.", 0)],
                         ids=["markdown", "html", "control"])
def test_T8_through_the_parser(tmp_path, capsys, before, expected):
    """T8 end to end; needs markdown-it-py, the parser the gate's workflow installs."""
    markdown_it = pytest.importorskip("markdown_it")
    md = markdown_it.MarkdownIt("commonmark")
    assert md.render(MARKDOWN + "\n\n" + FOOTER) == md.render(HTML + "\n\n" + FOOTER), "precondition"
    assert GATE.main(["--event", str(_event(tmp_path, before))]) == expected, capsys.readouterr().out
