_LIB_CANDIDATES = ("/usr/lib/softhsm/libsofthsm2.so", "/usr/lib/x86_64-linux-gnu/softhsm/libsofthsm2.so",
                   "/usr/lib64/pkcs11/libsofthsm2.so", "/usr/local/lib/softhsm/libsofthsm2.so",
                   "/opt/homebrew/lib/softhsm/libsofthsm2.so")


def _find_softhsm():
    lib = os.environ.get("PROOFBUNDLE_TEST_SOFTHSM2_LIB") or next(
        (p for p in _LIB_CANDIDATES if os.path.isfile(p)), None)
    util = os.environ.get("PROOFBUNDLE_TEST_SOFTHSM2_UTIL") or shutil.which("softhsm2-util")
    if not lib or not util or not os.path.isfile(lib) or not os.path.isfile(util):
        pytest.skip("SoftHSM2 (libsofthsm2.so and softhsm2-util) not found; set PROOFBUNDLE_TEST_SOFTHSM2_LIB "
                    "and PROOFBUNDLE_TEST_SOFTHSM2_UTIL", allow_module_level=True)
    return os.path.abspath(lib), os.path.abspath(util)


LIB, UTIL = _find_softhsm()
PIN_VAR = "PB_TEST_TOKEN_PIN"


def _uri(**attrs) -> str:
    path = ";".join(f"{k}={v}" for k, v in attrs.items())
    return f"pkcs11:{path}?module-path={LIB}"


class _Token:
    """The run's own token: its directory, its PIN and the keys this run put on it."""

    def __init__(self, base: Path):
        self.base = base
        self.pin = secrets.token_hex(8)
        self.so_pin = secrets.token_hex(8)
        (base / "tokens").mkdir()
        self.conf = base / "softhsm2.conf"
        self.conf.write_text(f"directories.tokendir = {base / 'tokens'}\nobjectstore.backend = file\n"
                             "log.level = ERROR\n", encoding="utf-8")
        self.known = Ed25519PrivateKey.generate()
        self.known_file = base / "known.key"
        save_signer(self.known, str(self.known_file))

    def env(self) -> dict:
        return {**os.environ, "SOFTHSM2_CONF": str(self.conf)}

    def init(self, label: str) -> None:
        r = subprocess.run([UTIL, "--init-token", "--free", "--label", label, "--so-pin", self.so_pin,
                            "--pin", self.pin, "--module", LIB], capture_output=True, text=True, env=self.env())
        assert r.returncode == 0, r.stderr[-300:]

    def delete(self, label: str) -> None:
        r = subprocess.run([UTIL, "--delete-token", "--token", label, "--module", LIB],
                           capture_output=True, text=True, env=self.env())
        assert r.returncode == 0, r.stderr[-300:]


def _open_session(label: str, pin: str):
    lib = pkcs11.lib(LIB)
    for slot in lib.get_slots(token_present=True):
        try:
            token = slot.get_token()
        except pkcs11.exceptions.PKCS11Error:
            continue
        if token.label == label:
            return token.open(user_pin=pin, rw=True)
    raise AssertionError(f"test token {label} not found")


def _populate(token: _Token) -> None:
    from asn1crypto.keys import PrivateKeyAlgorithmId
    from pkcs11 import Attribute, KeyType, ObjectClass
    from pkcs11.util.ec import encode_named_curve_parameters

    ed25519 = encode_named_curve_parameters(PrivateKeyAlgorithmId.unmap("ed25519"))
    ed448 = encode_named_curve_parameters(PrivateKeyAlgorithmId.unmap("ed448"))
    with _open_session("pb-test", token.pin) as s:
        params = s.create_domain_parameters(KeyType.EC_EDWARDS, {Attribute.EC_PARAMS: ed25519}, local=True)
        params.generate_keypair(store=True, label="ed", id=b"\x01")
        seed = token.known.private_bytes(Encoding.Raw, PrivateFormat.Raw, NoEncryption())
        pub = token.known.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)
        common = {Attribute.KEY_TYPE: KeyType.EC_EDWARDS, Attribute.TOKEN: True, Attribute.EC_PARAMS: ed25519}
        s.create_object({**common, Attribute.CLASS: ObjectClass.PRIVATE_KEY, Attribute.PRIVATE: True,
                         Attribute.SENSITIVE: True, Attribute.SIGN: True, Attribute.LABEL: "known",
                         Attribute.ID: b"\x02", Attribute.VALUE: seed})
        s.create_object({**common, Attribute.CLASS: ObjectClass.PUBLIC_KEY, Attribute.VERIFY: True,
                         Attribute.LABEL: "known", Attribute.ID: b"\x02", Attribute.EC_POINT: b"\x04\x20" + pub})
        # a private key whose public object is missing
        lone = Ed25519PrivateKey.generate().private_bytes(Encoding.Raw, PrivateFormat.Raw, NoEncryption())
        s.create_object({**common, Attribute.CLASS: ObjectClass.PRIVATE_KEY, Attribute.PRIVATE: True,
                         Attribute.SENSITIVE: True, Attribute.SIGN: True, Attribute.LABEL: "nopub",
                         Attribute.ID: b"\x05", Attribute.VALUE: lone})
        # two key pairs under one label
        params.generate_keypair(store=True, label="dup", id=b"\x06")
        params.generate_keypair(store=True, label="dup", id=b"\x07")
        # the wrong mechanisms: RSA, ECDSA P-256 and Ed448
        s.generate_keypair(KeyType.RSA, 2048, store=True, label="rsa", id=b"\x03")
        ec = s.create_domain_parameters(KeyType.EC, {Attribute.EC_PARAMS: encode_named_curve_parameters("secp256r1")},
                                        local=True)
        ec.generate_keypair(store=True, label="p256", id=b"\x04")
        e448 = s.create_domain_parameters(KeyType.EC_EDWARDS, {Attribute.EC_PARAMS: ed448}, local=True)
        e448.generate_keypair(store=True, label="ed448", id=b"\x08")
        # an Ed25519 key that may not sign (CKA_SIGN false), with its public object
        quiet = Ed25519PrivateKey.generate()
        s.create_object({**common, Attribute.CLASS: ObjectClass.PRIVATE_KEY, Attribute.PRIVATE: True,
                         Attribute.SENSITIVE: True, Attribute.SIGN: False, Attribute.LABEL: "nosign",
                         Attribute.ID: b"\x0b",
                         Attribute.VALUE: quiet.private_bytes(Encoding.Raw, PrivateFormat.Raw, NoEncryption())})
        s.create_object({**common, Attribute.CLASS: ObjectClass.PUBLIC_KEY, Attribute.VERIFY: True,
                         Attribute.LABEL: "nosign", Attribute.ID: b"\x0b",
                         Attribute.EC_POINT: b"\x04\x20" + quiet.public_key().public_bytes(Encoding.Raw,
                                                                                        PublicFormat.Raw)})
        # an Ed25519 private key whose public object claims another curve
        mixed = Ed25519PrivateKey.generate()
        s.create_object({**common, Attribute.CLASS: ObjectClass.PRIVATE_KEY, Attribute.PRIVATE: True,
                         Attribute.SENSITIVE: True, Attribute.SIGN: True, Attribute.LABEL: "mixed",
                         Attribute.ID: b"\x0a",
                         Attribute.VALUE: mixed.private_bytes(Encoding.Raw, PrivateFormat.Raw, NoEncryption())})
        s.create_object({Attribute.KEY_TYPE: KeyType.EC_EDWARDS, Attribute.TOKEN: True, Attribute.EC_PARAMS: ed448,
                         Attribute.CLASS: ObjectClass.PUBLIC_KEY, Attribute.VERIFY: True, Attribute.LABEL: "mixed",
                         Attribute.ID: b"\x0a",
                         Attribute.EC_POINT: b"\x04\x20" + mixed.public_key().public_bytes(Encoding.Raw,
                                                                                        PublicFormat.Raw)})
        # an Ed25519 private key whose one public object (same id) is that of another key
        signing, stated = Ed25519PrivateKey.generate(), Ed25519PrivateKey.generate()
        s.create_object({**common, Attribute.CLASS: ObjectClass.PRIVATE_KEY, Attribute.PRIVATE: True,
                         Attribute.SENSITIVE: True, Attribute.SIGN: True, Attribute.LABEL: "xpair",
                         Attribute.ID: b"\x0c",
                         Attribute.VALUE: signing.private_bytes(Encoding.Raw, PrivateFormat.Raw, NoEncryption())})
        s.create_object({**common, Attribute.CLASS: ObjectClass.PUBLIC_KEY, Attribute.VERIFY: True,
                         Attribute.LABEL: "xpair", Attribute.ID: b"\x0c",
                         Attribute.EC_POINT: b"\x04\x20" + stated.public_key().public_bytes(Encoding.Raw,
                                                                                         PublicFormat.Raw)})


@pytest.fixture(scope="module")
def token(tmp_path_factory):
    base = tmp_path_factory.mktemp("softhsm")
    tok = _Token(base)
    old = os.environ.get("SOFTHSM2_CONF")
    os.environ["SOFTHSM2_CONF"] = str(tok.conf)
    tok.init("pb-test")
    tok.init("pb-gone")
    tok.init("pb-twin")
    tok.init("pb-twin")
    lib = pkcs11.lib(LIB)
    lib.reinitialize()   # the module reads SOFTHSM2_CONF when it is initialised
    _populate(tok)
    yield tok
    lib.reinitialize()
    if old is None:
        os.environ.pop("SOFTHSM2_CONF", None)
    else:
        os.environ["SOFTHSM2_CONF"] = old


@pytest.fixture
def pin(token, monkeypatch):
    monkeypatch.setenv(PIN_VAR, token.pin)
    return pin_from_env(PIN_VAR)


def _claim():
    claim, _ = build_eval_claim(
        suite="s", suite_version="v1", metric="acc", comparator=">=", threshold="0.80", score="0.90",
        n=100, model_id="m", dataset_id="d", issuer="x", timestamp="2026-07-01T12:00:00Z",
        model_salt=b"0" * 16, dataset_salt=b"1" * 16)
    return claim


def _run(token: _Token, *args, pin_value=None):
    import pkcs11 as _p
    env = token.env()
    env["PYTHONPATH"] = os.pathsep.join([str(REPO / "src"), str(Path(_p.__file__).resolve().parent.parent)])
    if pin_value is not None:
        env[PIN_VAR] = pin_value
    return subprocess.run([sys.executable, "-m", "proofbundle.cli", *args], capture_output=True, text=True,
                          cwd=REPO, env=env, stdin=subprocess.DEVNULL)


# ── round trip with the existing verifier ─────────────────────────────────────────────────────────────

def test_token_receipt_is_judged_by_the_existing_verifier(token, pin):
    with Pkcs11Signer.open(_uri(token="pb-test", object="ed", type="private"), pin=pin) as signer:
        bundle = emit_eval_receipt(_claim(), signer)
        record = signer.sign_bytes(b"raw bytes")
    assert verify_bundle(bundle).ok
    assert classify_eval_claim(bundle)[0] == CLAIM_VALID
    assert decode_eval_claim(bundle)["issuer"] == signer.key_id == record.key_id
    assert record.algorithm == "ed25519" and len(record.signature) == 64


def test_token_with_the_same_key_signs_byte_identical_receipts(token, pin, tmp_path):
    claim = _claim()
    template = tmp_path / "predicate.json"
    assert cli.main(["decision", "init", "--out", str(template)]) == 0
    predicate = json.loads(template.read_text(encoding="utf-8"))
    with Pkcs11Signer.open(_uri(token="pb-test", object="known"), pin=pin) as signer:
        assert signer.public_key_raw() == token.known.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)
        assert emit_eval_receipt(claim, signer) == emit_eval_receipt(claim, token.known)
        assert signer.sign(b"release payload") == token.known.sign(b"release payload")
        assert emit_decision_receipt(predicate, signer, strict=False) == \
            emit_decision_receipt(predicate, token.known, strict=False)


def test_the_id_attribute_selects_the_key(token, pin):
    with Pkcs11Signer.open(_uri(token="pb-test", id="%02"), pin=pin) as signer:
        assert signer.public_key_raw() == token.known.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)


def test_cli_round_trip_emit_eval_show_eval_emit_verify(token, tmp_path):
    claim = tmp_path / "claim.json"
    claim.write_text(json.dumps(_claim()), encoding="utf-8")
    receipt = tmp_path / "receipt.json"
    uri = _uri(token="pb-test", object="known")
    r = _run(token, "emit-eval", "--claim", str(claim), "--out", str(receipt), "--token-uri", uri,
             "--token-pin-env", PIN_VAR, pin_value=token.pin)
    assert r.returncode == 0, r.stderr
    assert token.pin not in r.stdout + r.stderr
    file_receipt = tmp_path / "file_receipt.json"
    r = _run(token, "emit-eval", "--claim", str(claim), "--out", str(file_receipt), "--key", str(token.known_file))
    assert r.returncode == 0, r.stderr
    assert receipt.read_bytes() == file_receipt.read_bytes()
    issuer = decode_eval_claim(json.loads(receipt.read_text(encoding="utf-8")))["issuer"]
    show = _run(token, "show-eval", str(receipt), "--expect-issuer", issuer)
    assert show.returncode == 0 and "=> OK" in show.stdout, show.stderr
    payload = tmp_path / "payload.bin"
    payload.write_bytes(b"artifact bytes")
    bundle = tmp_path / "bundle.json"
    r = _run(token, "emit", "--payload-file", str(payload), "--out", str(bundle), "--token-uri",
             _uri(token="pb-test", object="ed"), "--token-pin-env", PIN_VAR, pin_value=token.pin)
    assert r.returncode == 0, r.stderr
    assert _run(token, "verify", str(bundle)).returncode == 0


def test_cli_round_trip_decision_emit_verify(token, tmp_path):
    predicate = tmp_path / "predicate.json"
    assert _run(token, "decision", "init", "--out", str(predicate)).returncode == 0
    envelope = tmp_path / "decision.json"
    r = _run(token, "decision", "emit", str(predicate), "--out", str(envelope), "--lenient",
             "--token-uri", _uri(token="pb-test", object="known"), "--token-pin-env", PIN_VAR, pin_value=token.pin)
    assert r.returncode == 0, r.stderr
    import base64
    pub = base64.b64encode(token.known.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)).decode()
    v = _run(token, "decision", "verify", str(envelope), "--pub", pub)
    assert v.returncode == 0, v.stdout + v.stderr


# ── the negative cases ────────────────────────────────────────────────────────────────────────────────

def test_wrong_pin_is_refused_and_not_shown(token, monkeypatch, tmp_path):
    wrong = "0" + token.pin[1:] if token.pin[0] != "0" else "1" + token.pin[1:]
    monkeypatch.setenv(PIN_VAR, wrong)
    with pytest.raises(SignerError, match="refused the PIN") as info:
        Pkcs11Signer.open(_uri(token="pb-test", object="ed"), pin=pin_from_env(PIN_VAR))
    assert wrong not in str(info.value) and token.pin not in str(info.value)
    payload = tmp_path / "p.bin"
    payload.write_bytes(b"x")
    out = tmp_path / "b.json"
    r = _run(token, "emit", "--payload-file", str(payload), "--out", str(out), "--token-uri",
             _uri(token="pb-test", object="ed"), "--token-pin-env", PIN_VAR, pin_value=wrong)
    assert r.returncode == 2 and not out.exists()
    assert wrong not in r.stdout + r.stderr and "Traceback" not in r.stderr


