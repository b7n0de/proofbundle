def test_token_gone_during_the_session_is_an_error_and_never_a_fallback(token, monkeypatch, tmp_path):
    """Measured on SoftHSM2 2.6.1: a token deleted by another process leaves the open session's key handle
    invalid (CKR_OBJECT_HANDLE_INVALID). The signer reports it; nothing is signed, nothing else signs."""
    from asn1crypto.keys import PrivateKeyAlgorithmId
    from pkcs11 import Attribute, KeyType
    from pkcs11.util.ec import encode_named_curve_parameters

    with _open_session("pb-gone", token.pin) as s:
        s.create_domain_parameters(
            KeyType.EC_EDWARDS,
            {Attribute.EC_PARAMS: encode_named_curve_parameters(PrivateKeyAlgorithmId.unmap("ed25519"))},
            local=True).generate_keypair(store=True, label="gone", id=b"\x09")
    monkeypatch.setenv(PIN_VAR, token.pin)
    signer = Pkcs11Signer.open(_uri(token="pb-gone", object="gone"), pin=pin_from_env(PIN_VAR))
    try:
        token.delete("pb-gone")
        with pytest.raises(SignerError, match="did not sign .ObjectHandleInvalid.*no fallback"):
            emit_eval_receipt(_claim(), signer)
        # The deleted token leaves a slot that cannot be read in this process: no token is chosen then,
        # not even another one, so a second token of the same name cannot hide behind the unreadable slot.
        with pytest.raises(SignerError, match="a slot of the module could not be read"):
            Pkcs11Signer.open(_uri(token="pb-test", object="ed"), pin=pin_from_env(PIN_VAR))
    finally:
        signer.close()
        pkcs11.lib(LIB).reinitialize()   # SoftHSM keeps a stale slot until the module is initialised again
    payload = tmp_path / "p.bin"
    payload.write_bytes(b"x")
    out = tmp_path / "b.json"
    r = _run(token, "emit", "--payload-file", str(payload), "--out", str(out), "--token-uri",
             _uri(token="pb-gone", object="gone"), "--token-pin-env", PIN_VAR, pin_value=token.pin)
    assert r.returncode == 2 and not out.exists() and "Traceback" not in r.stderr


