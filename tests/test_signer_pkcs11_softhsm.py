"""The PKCS#11 signer against a real software token (SoftHSM2), created by this run (Z380).

Nothing here touches a real token or a real key: the session fixture initialises a fresh SoftHSM2 token in a
temporary directory, with a PIN and an SO PIN this run draws at random, and every key on it is generated by
this run or imported from a key this run generated.

The module is skipped when either part is missing: the ``python-pkcs11`` package (the ``[pkcs11]`` extra) or
the SoftHSM2 module and its ``softhsm2-util``. They are found through ``PROOFBUNDLE_TEST_SOFTHSM2_LIB`` and
``PROOFBUNDLE_TEST_SOFTHSM2_UTIL``, or at the paths the common packages install them to.

What is measured:

* the round trip: a receipt the token signs is judged by the existing verifier, through the library and
  through the command line (``emit-eval`` then ``show-eval``, ``emit`` then ``verify``, ``decision emit``
  then ``decision verify``);
* a token holding the same key as a key file signs byte-identical receipts, so the verifier cannot tell the
  two apart and needs nothing new;
* the negative cases of the order: a wrong PIN, a missing object, a wrong mechanism (an RSA, a P-256 and an
  Ed448 key), and a token that is gone while its session is open; plus an ambiguous selection, a private key
  without its public object, a public object of another key, and a URI that selects a public object;
* the session: a second signer on an open token is refused naming the first, and a signer closes when the
  command ends or when it is collected;
* no case falls back to a key file, and the PIN appears in no output.
"""
