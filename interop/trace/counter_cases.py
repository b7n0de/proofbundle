"""Counter-cases for the TRACE comparison, derived from the specification, one rule per case.

Every case is built here, by this file's own signer, from fixed seeds: nothing is taken from the
TRACE reference or from trace-tests, so the cases are MIT like the rest of this repository and can be
regenerated byte for byte. Each case names the section of ``spec/trace-v0.2.md`` (trace-spec at
a131c640) its expectation is read from, and says when the expectation is DERIVED (the rule lives in a
standard the specification invokes) or CONTESTED (the specification and its schema disagree).

Expectation values: ``accept``, ``reject``, or ``n/a`` when no normative text decides the case.
"""
from __future__ import annotations

import base64
import copy
import json
from typing import Any, Dict, List

import rfc8785
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives.asymmetric.utils import decode_dss_signature

NOW = 1792000000
PROFILE = "tag:agentrust-io.com,2026:trace-v0.2"
P256_N = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551


def b64(raw: bytes) -> str:
    return base64.urlsafe_b64encode(raw).rstrip(b"=").decode("ascii")


ED = Ed25519PrivateKey.from_private_bytes(bytes(range(32)))
ED_OTHER = Ed25519PrivateKey.from_private_bytes(bytes(range(1, 33)))
P256 = ec.derive_private_key(0x1F2E3D4C5B6A79881726354453627180A9B8C7D6E5F40312233445566778899A, ec.SECP256R1())
P384 = ec.derive_private_key(
    0x0102030405060708090A0B0C0D0E0F101112131415161718191A1B1C1D1E1F20212223242526272829, ec.SECP384R1())


def ed_jwk(key=ED) -> Dict[str, str]:
    raw = key.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    return {"kty": "OKP", "crv": "Ed25519", "x": b64(raw)}


def ec_jwk(key) -> Dict[str, str]:
    n = 32 if isinstance(key.curve, ec.SECP256R1) else 48
    nums = key.public_key().public_numbers()
    return {"kty": "EC", "crv": "P-256" if n == 32 else "P-384",
            "x": b64(nums.x.to_bytes(n, "big")), "y": b64(nums.y.to_bytes(n, "big"))}


def base_record(jwk: Dict[str, Any], **changes: Any) -> Dict[str, Any]:
    rec = {
        "eat_profile": PROFILE,
        "iat": NOW - 60,
        "subject": "spiffe://trust.example.org/agent/payments/prod",
        "model": {"provider": "example-provider", "model_id": "example-model", "version": "20251001",
                  "weights_digest": "sha256:" + "a3" * 32},
        "runtime": {"platform": "software-only", "measurement": "sha384:" + "c9" * 48, "nonce": "challenge-1"},
        "policy": {"bundle_hash": "sha256:" + "b2" * 32, "enforcement_mode": "enforce", "version": "1.2.0"},
        "data_class": "confidential",
        "tool_transcript": {"hash": "sha256:" + "d4" * 32, "call_count": 3,
                            "transcript_uri": "https://registry.example.org/transcript/1"},
        "build_provenance": {"slsa_level": 2, "builder": "https://builder.example.org",
                             "digest": "sha256:" + "e5" * 32},
        "appraisal": {"status": "none", "verifier": "https://verifier.example.org"},
        "transparency": "https://registry.example.org/claim/1",
        "cnf": {"jwk": copy.deepcopy(jwk)},
    }
    rec.update(changes)
    return rec


def sign_embedded(rec: Dict[str, Any], key=ED) -> Dict[str, Any]:
    body = {k: v for k, v in rec.items() if k != "signature"}
    return dict(body, signature=b64(key.sign(rfc8785.dumps(body))))


def dumps(obj: Any) -> bytes:
    return json.dumps(obj, ensure_ascii=False).encode("utf-8")


def _ecdsa_raw(key, data: bytes) -> bytes:
    n = 32 if isinstance(key.curve, ec.SECP256R1) else 48
    r, s = decode_dss_signature(key.sign(data, ec.ECDSA(hashes.SHA256() if n == 32 else hashes.SHA384())))
    return r.to_bytes(n, "big") + s.to_bytes(n, "big")


def jws(rec: Dict[str, Any], alg: str = "EdDSA", key=ED, header: Any = None, payload: Any = None,
        raw_header: Any = None, signature: Any = None) -> bytes:
    h = b64(raw_header if raw_header is not None else
            json.dumps(header if header is not None else {"alg": alg}, separators=(",", ":")).encode())
    p = b64(payload if payload is not None else rfc8785.dumps(rec))
    signing_input = (h + "." + p).encode("ascii")
    if signature is None:
        signature = key.sign(signing_input) if isinstance(key, Ed25519PrivateKey) else _ecdsa_raw(key, signing_input)
    return (h + "." + p + "." + b64(signature)).encode("ascii")


def _case(cases: List[Dict[str, Any]], cid: str, form: str, section: str, description: str,
          expected: str, raw: bytes, *, basis: str = "normative", jwk: Any = None, **options: Any) -> None:
    case = {"id": cid, "corpus": "counter-case", "form": form, "section": section, "description": description,
            "expected": expected, "basis": basis, "raw": raw, "jwk": jwk if jwk is not None else ed_jwk(),
            "now": NOW, "max_age_seconds": 86400, "max_future_skew_seconds": 300, "expected_nonce": None,
            "expected_policy_hashes": None, "expected_subjects": None, "expected_transcript_hash": None,
            "accepted_profiles": None, "pb_keys": None, "reference_input_gap": None}
    case.update(options)
    if form == "jws-compact":
        case["reference"] = "n/a: the reference implements the embedded form only (sign.py verify_record)"
    cases.append(case)


def _leaves(obj: Any, path=()):
    if isinstance(obj, dict):
        for k, v in obj.items():
            yield from _leaves(v, path + (k,))
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            yield from _leaves(v, path + (i,))
    else:
        yield path


def _changed(value: Any) -> Any:
    if isinstance(value, bool):
        return not value
    if isinstance(value, int):
        return value + 1
    return value[:-1] + ("0" if value[-1:] != "0" else "1")


def _set(obj: Dict[str, Any], path, value: Any) -> Dict[str, Any]:
    out = copy.deepcopy(obj)
    cur = out
    for step in path[:-1]:
        cur = cur[step]
    cur[path[-1]] = value
    return out


def _get(obj: Any, path) -> Any:
    for step in path:
        obj = obj[step]
    return obj


def build() -> List[Dict[str, Any]]:
    cases: List[Dict[str, Any]] = []
    E, J = "embedded", "jws-compact"
    jwk = ed_jwk()
    base = base_record(jwk)
    signed = sign_embedded(base)

    # ---- embedded form, run against both sides ------------------------------------------------
    _case(cases, "E-00-valid", E, "3.2.2 (embedded)", "well-formed record, signed by the trusted key", "accept",
          dumps(signed))
    for path in _leaves(base):
        if path == ("eat_profile",):
            continue
        name = ".".join(map(str, path))
        _case(cases, f"E-F-{name}", E, "3.2.2, 3.3 step 1",
              f"signed field {name} changed once after signing", "reject",
              dumps(_set(signed, path, _changed(_get(signed, path)))))
    _case(cases, "E-F-eat_profile", E, "3.2.2, Changes from v0.1",
          "eat_profile changed after signing (to the v0.1 identifier)", "reject",
          dumps(dict(signed, eat_profile="tag:agentrust.io,2026:trace-v0.1")))
    _case(cases, "E-ADD-references", E, "3.1.2 rule 2",
          "references added after signing", "reject",
          dumps(dict(signed, references=[{"rel": "behavior-trace", "id": "x", "resolver": "https://r.example"}])))
    _case(cases, "E-REMOVE-tool_transcript", E, "3.2.2", "tool_transcript removed after signing", "reject",
          dumps({k: v for k, v in signed.items() if k != "tool_transcript"}))
    _case(cases, "E-KEY-other", E, "3.3 step 1",
          "signed by, and naming, a key the relying party does not trust", "reject",
          dumps(sign_embedded(base_record(ed_jwk(ED_OTHER)), ED_OTHER)))
    _case(cases, "E-CNF-other", E, "3.2.2 (signature made by the key in cnf)",
          "signed by the trusted key, cnf names another key", "reject",
          dumps(sign_embedded(base_record(ed_jwk(ED_OTHER)), ED)))
    ec_rec = base_record(ec_jwk(P256))
    body = {k: v for k, v in ec_rec.items() if k != "signature"}
    _case(cases, "E-EC-embedded", E, "3.2.2 (embedded), 3.2.1",
          "embedded ES256 signature (raw r||s, base64url) by a trusted P-256 cnf key", "n/a",
          dumps(dict(body, signature=b64(_ecdsa_raw(P256, rfc8785.dumps(body))))), jwk=ec_jwk(P256),
          basis="no normative text: 3.2.2 fixes no encoding for an embedded ECDSA signature")
    for cid, iat, exp in (("E-FRESH-age-edge", NOW - 86400, "accept"), ("E-FRESH-expired", NOW - 86401, "reject"),
                          ("E-FRESH-skew-edge", NOW + 300, "accept"), ("E-FRESH-future", NOW + 301, "reject")):
        _case(cases, cid, E, "3.2.2 (freshness), 3.3 step 2", f"iat = now {iat - NOW:+d}s", exp,
              dumps(sign_embedded(base_record(jwk, iat=iat))))
    _case(cases, "E-NONCE-match", E, "3.2.2 (nonce)", "relying party challenge echoed", "accept", dumps(signed),
          expected_nonce="challenge-1")
    _case(cases, "E-NONCE-mismatch", E, "3.2.2 (nonce)", "relying party challenge not echoed", "reject",
          dumps(signed), expected_nonce="challenge-2")
    no_nonce = base_record(jwk)
    del no_nonce["runtime"]["nonce"]
    _case(cases, "E-NONCE-absent", E, "3.2.2 (nonce)", "challenge issued, record carries no runtime.nonce",
          "reject", dumps(sign_embedded(no_nonce)), expected_nonce="challenge-1")
    _case(cases, "E-POLICY-hash-wrong", E, "3.3 step 5",
          "the relying party expects another policy bundle hash", "reject", dumps(signed),
          expected_policy_hashes=["sha256:" + "b3" * 32],
          reference_input_gap="verify_record takes no expected policy hash")
    _case(cases, "E-POLICY-hash-right", E, "3.3 step 5", "the relying party expects this policy bundle hash",
          "accept", dumps(signed), expected_policy_hashes=["sha256:" + "b2" * 32],
          reference_input_gap="verify_record takes no expected policy hash")
    _case(cases, "E-TRANSCRIPT-hash-wrong", E, "none (3.3.3 informative)",
          "the relying party holds a transcript with another hash", "n/a", dumps(signed),
          basis="no normative verifier rule binds tool_transcript.hash to transcript bytes",
          expected_transcript_hash="sha256:" + "d5" * 32,
          reference_input_gap="verify_record takes no transcript hash")
    _case(cases, "E-SUBJECT-out-of-scope", E, "none (relying-party scope)",
          "the subject is outside the relying party's scope", "n/a", dumps(signed),
          basis="no normative verifier rule; scope is relying-party policy",
          expected_subjects=["spiffe://trust.example.org/agent/payments/dev"],
          reference_input_gap="verify_record takes no subject scope")
    text = dumps(signed).decode()
    _case(cases, "E-DUP-last-is-signed", E, "3.2.2 (RFC 8785 over I-JSON, RFC 7493 section 2.3)",
          "data_class twice; the LAST value is the signed one", "reject",
          text.replace('"data_class": "confidential"', '"data_class": "public", "data_class": "confidential"').encode(),
          basis="derived: RFC 8785 is defined over I-JSON, which forbids duplicate member names")
    _case(cases, "E-DUP-first-is-signed", E, "3.2.2 (RFC 8785 over I-JSON, RFC 7493 section 2.3)",
          "data_class twice; the FIRST value is the signed one", "reject",
          text.replace('"data_class": "confidential"', '"data_class": "confidential", "data_class": "public"').encode(),
          basis="derived: RFC 8785 is defined over I-JSON, which forbids duplicate member names")
    _case(cases, "E-DUP-nested-last-is-signed", E, "3.2.2 (RFC 8785 over I-JSON, RFC 7493 section 2.3)",
          "policy.enforcement_mode twice; the LAST value is the signed one", "reject",
          text.replace('"enforcement_mode": "enforce"',
                       '"enforcement_mode": "silent", "enforcement_mode": "enforce"').encode(),
          basis="derived: RFC 8785 is defined over I-JSON, which forbids duplicate member names")
    _case(cases, "E-DUP-signature", E, "3.2.2 (RFC 8785 over I-JSON, RFC 7493 section 2.3)",
          "signature twice; the LAST value is the valid one", "reject",
          text.replace('"signature": "', '"signature": "' + b64(bytes(64)) + '", "signature": "').encode(),
          basis="derived: RFC 8785 is defined over I-JSON, which forbids duplicate member names")
    for cid, path, value in (("E-UNKNOWN-top-exp", ("exp",), NOW + 3600),
                             ("E-UNKNOWN-runtime-quote", ("runtime", "quote"), "AAAA"),
                             ("E-UNKNOWN-cnf-kid", ("cnf", "kid"), "k1")):
        _case(cases, cid, E, "Authority and conformance claims; schema additionalProperties false",
              f"a signed member {'.'.join(path)} the schema does not define", "reject",
              dumps(sign_embedded(_set(base, path, value))))
    _case(cases, "E-UNKNOWN-cnf-jwk-use", E, "schema cnf.jwk additionalProperties canonicalizableValue",
          "a signed cnf.jwk member the schema leaves open (use)", "accept",
          dumps(sign_embedded(base_record(dict(jwk, use="sig")))))
    _case(cases, "E-UNSIGNED", E, "3.2.2", "no signature member and no envelope", "reject", dumps(base))
    sig = signed["signature"]
    _case(cases, "E-SIG-padded", E, "3.2.2 (canonical base64url)", "signature with '==' padding", "reject",
          dumps(dict(signed, signature=sig + "==")))
    _case(cases, "E-SIG-std-alphabet", E, "3.2.2 (canonical base64url)",
          "signature in the standard alphabet (+/)", "reject" if ("-" in sig or "_" in sig) else "accept",
          dumps(dict(signed, signature=sig.replace("-", "+").replace("_", "/"))))
    _case(cases, "E-INT-above-range", E, "3.2.2 (safe-integer range)", "call_count 2^53 (unsigned change)",
          "reject", text.replace('"call_count": 3', '"call_count": 9007199254740992').encode())
    _case(cases, "E-NAN", E, "3.2.2 (RFC 8785), RFC 8259 section 6", "call_count NaN", "reject",
          text.replace('"call_count": 3', '"call_count": NaN').encode())
    _case(cases, "E-LONE-SURROGATE", E, "3.2.2 (RFC 8785), RFC 7493 section 2.1", "data_class is a lone surrogate",
          "reject", text.replace('"data_class": "confidential"', '"data_class": "\\ud800"').encode())
    hw = base_record(jwk, origin={"kind": "third-party-control-plane", "producer": "vendor-x"})
    hw["runtime"]["platform"] = "intel-tdx"
    _case(cases, "E-ORIGIN-hardware", E, "3.1.1", "origin not self with a hardware platform", "reject",
          dumps(sign_embedded(hw)))
    pm = {"measurement": "sha384:" + "c9" * 48, "layers": {"pcr:0": {"outcome": "established"}}}
    pm_rec = base_record(jwk, appraisal={"status": "warning", "verifier": "https://verifier.example.org",
                                         "platform_measurement": pm})
    pm_rec["runtime"]["platform"] = "tpm2"
    _case(cases, "E-PM-valid", E, "3.1.5 (main revision)", "a valid appraisal.platform_measurement", "accept",
          dumps(sign_embedded(pm_rec)))
    bad_pm = copy.deepcopy(pm_rec)
    bad_pm["appraisal"]["platform_measurement"]["measurement"] = "sha384:" + "00" * 48
    _case(cases, "E-PM-measurement-mismatch", E, "3.1.5 (main revision)",
          "platform_measurement.measurement differs from runtime.measurement", "reject",
          dumps(sign_embedded(bad_pm)))
    _case(cases, "E-SUBJECT-trailing-newline", E, "schema subject pattern (ECMA-262 $)",
          "subject ending in a line feed", "reject",
          dumps(sign_embedded(base_record(jwk, subject="spiffe://trust.example.org/agent/a\n"))))
    for cid, uri, exp in (("E-URI-ipv6", "https://[::1]:8443/v", "accept"),
                          ("E-URI-zone-id", "https://[fe80::1%eth0]/v", "reject"),
                          ("E-URI-space", "https://verifier.example.org/a b", "reject"),
                          ("E-URI-relative", "/verifier", "reject"),
                          ("E-URI-non-ascii", "https://verifier.example.org/é", "reject"),
                          ("E-URI-empty-port", "https://verifier.example.org:/v", "accept"),
                          ("E-URI-bad-percent", "https://verifier.example.org/%zz", "reject")):
        _case(cases, cid, E, "schema format uri (JSON Schema 2020-12 section 7.3.5, RFC 3986)",
              f"appraisal.verifier = {uri!r}", exp,
              dumps(sign_embedded(base_record(jwk, appraisal={"status": "none", "verifier": uri}))),
              basis="derived: RFC 3986 section 3")
    _case(cases, "E-NUMBER-whole-float", E, "3.2.2 (what counts as an integer)",
          "iat written as a fraction with zero part", "accept",
          dumps(signed).replace(b'"iat": %d' % (NOW - 60), b'"iat": %d.0' % (NOW - 60)))
    no_tx = {k: v for k, v in base.items() if k != "transparency"}
    _case(cases, "E-OPTIONAL-transparency-absent", E, "registry-anchor-v1 section 6; schema",
          "no transparency member", "accept", dumps(sign_embedded(no_tx)))
    no_tt = {k: v for k, v in base.items() if k != "tool_transcript"}
    _case(cases, "E-CONTESTED-tool_transcript-absent", E, "3.1 table vs schema required set",
          "no tool_transcript member", "n/a", dumps(sign_embedded(no_tt)),
          basis="contested: 3.1 says every field without OPTIONAL is required and does not mark "
                "tool_transcript OPTIONAL; the schema does not require it")
    _case(cases, "E-PRIVATE-cnf-d", E, "schema cnf.jwk not d", "cnf.jwk carries a private member d", "reject",
          dumps(sign_embedded(base_record(dict(jwk, d=b64(bytes(32)))))))

    # ---- compact JWS form: proofbundle only; the reference has no enveloping path -------------
    for alg, key, k in (("EdDSA", ED, jwk), ("ES256", P256, ec_jwk(P256)), ("ES384", P384, ec_jwk(P384))):
        _case(cases, f"J-{alg}-valid", J, "3.2, 3.2.1, 3.2.2 (enveloping)", f"compact JWS, alg {alg}", "accept",
              jws(base_record(k), alg, key), jwk=k)
    es = jws(base_record(ec_jwk(P256)), "ES256", P256).decode().split(".")
    s = base64.urlsafe_b64decode(es[2] + "==")
    high = s[:32] + (P256_N - int.from_bytes(s[32:], "big")).to_bytes(32, "big")
    _case(cases, "J-ES256-other-s", J, "3.2.1; RFC 7518 section 3.4",
          "the (r, n - s) spelling of a valid ES256 signature", "accept",
          f"{es[0]}.{es[1]}.{b64(high)}".encode(), jwk=ec_jwk(P256),
          basis="derived: RFC 7518 does not require low s")
    canonical_payload = b64(rfc8785.dumps(base))
    _case(cases, "J-alg-none", J, "3.2.1, 3.2.2", "alg none with an empty signature segment", "reject",
          (b64(b'{"alg":"none"}') + "." + canonical_payload + ".").encode())
    _case(cases, "J-alg-HS256", J, "3.2.1", "alg HS256 keyed with the public key bytes", "reject",
          jws(base, header={"alg": "HS256"}, key=ED))
    _case(cases, "J-alg-RS256", J, "3.2.1", "alg RS256", "reject", jws(base, header={"alg": "RS256"}, key=ED))
    ed_token = jws(base_record(ec_jwk(P256)), "EdDSA", ED).decode().split(".")
    _case(cases, "J-alg-confusion", J, "3.2.1, 3.3 step 1",
          "header says ES256, the signature is EdDSA, the relying party holds a P-256 key", "reject",
          (b64(b'{"alg":"ES256"}') + "." + ed_token[1] + "." + ed_token[2]).encode(), jwk=ec_jwk(P256))
    _case(cases, "J-alg-key-mismatch", J, "3.2.1, 3.3 step 1",
          "EdDSA token, the relying party holds only a P-256 key", "reject", jws(base, "EdDSA", ED), jwk=ec_jwk(P256))
    _case(cases, "J-key-other", J, "3.3 step 1", "signed by and naming an untrusted key", "reject",
          jws(base_record(ed_jwk(ED_OTHER)), "EdDSA", ED_OTHER))
    _case(cases, "J-cnf-other", J, "3.2.2", "signed by the trusted key, cnf names another key", "reject",
          jws(base_record(ed_jwk(ED_OTHER)), "EdDSA", ED))
    _case(cases, "J-crit", J, "RFC 7515 section 4.1.11", "crit names an extension nobody understands", "reject",
          jws(base, header={"alg": "EdDSA", "crit": ["exp"], "exp": 1}, key=ED), basis="derived: RFC 7515")
    _case(cases, "J-header-jwk", J, "3.3 step 1 (trust from the relying party)",
          "the header offers its own jwk (the signer's) and the signer is untrusted", "reject",
          jws(base_record(ed_jwk(ED_OTHER)), header={"alg": "EdDSA", "jwk": ed_jwk(ED_OTHER)}, key=ED_OTHER))
    _case(cases, "J-b64-false", J, "RFC 7797 (b64 changes the signing input)", "b64 false in the header",
          "reject", jws(base, header={"alg": "EdDSA", "b64": False, "crit": ["b64"]}, key=ED),
          basis="derived: RFC 7515 section 4.1.11, RFC 7797")
    _case(cases, "J-payload-not-canonical", J, "3.2.2 (signature over the canonical form)",
          "payload is json.dumps with spaces, not RFC 8785", "reject", jws(base, payload=json.dumps(base).encode()),
          basis="derived: a JWS signs the payload bytes, 3.2.2 binds the signature to the RFC 8785 form")
    _case(cases, "J-payload-signature-member", J, "3.1 (enveloping profiles omit signature)",
          "the payload carries a signature member", "reject", jws(dict(base, signature=b64(bytes(64)))))
    _case(cases, "J-dup-header", J, "RFC 7515 section 4", "alg twice in the protected header", "reject",
          jws(base, raw_header=b'{"alg":"EdDSA","alg":"none"}', key=ED),
          basis="derived: RFC 7515 section 4 lets a parser reject duplicate header names")
    dup_payload = rfc8785.dumps(base).replace(b'"data_class":"confidential"',
                                              b'"data_class":"public","data_class":"confidential"')
    _case(cases, "J-dup-payload", J, "3.2.2 (RFC 8785 over I-JSON)", "data_class twice in the payload", "reject",
          jws(base, payload=dup_payload), basis="derived: RFC 7493 section 2.3")
    token = jws(base).decode().split(".")
    for path in (("iat",), ("subject",), ("policy", "bundle_hash"), ("cnf", "jwk", "x"), ("runtime", "measurement")):
        name = ".".join(path)
        p = b64(rfc8785.dumps(_set(base, path, _changed(_get(base, path)))))
        _case(cases, f"J-F-{name}", J, "3.2.2, 3.3 step 1", f"signed field {name} changed once after signing",
              "reject", f"{token[0]}.{p}.{token[2]}".encode())
    _case(cases, "J-FRESH-expired", J, "3.2.2 (freshness)", "iat = now -86401s", "reject",
          jws(base_record(jwk, iat=NOW - 86401)))
    _case(cases, "J-POLICY-hash-wrong", J, "3.3 step 5", "the relying party expects another policy bundle hash",
          "reject", jws(base), expected_policy_hashes=["sha256:" + "b3" * 32])
    return cases
